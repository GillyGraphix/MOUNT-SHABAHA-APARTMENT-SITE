<style>
    .warp-star {
        position: absolute;
        background: white;
        border-radius: 50%;
        opacity: 0.8;
        animation: twinkle var(--duration, 3s) infinite ease-in-out;
        will-change: transform, opacity, top;
    }

    @keyframes twinkle {
        0%, 100% { opacity: 0.2; transform: scale(0.8); }
        50% { opacity: 1; transform: scale(1.2); }
    }
</style>

<script>
    document.addEventListener('DOMContentLoaded', () => {
        
        // SCRIPT MPYA YA NYOTA (Imesawazishwa bila kusumbua Scroll ya simu)
        const container = document.getElementById('star-container');
        if (!container) return;
        container.innerHTML = '';

        const count = 100; 
        const stars = [];

        for (let i = 0; i < count; i++) {
            const s = document.createElement('div');
            s.className = 'warp-star';

            const x = Math.random() * 100;
            const y = Math.random() * 100;

            const isStatic = Math.random() < 0.3;
            const z = isStatic ? 0 : 0.2 + Math.random() * 0.6; 
            const size = isStatic ? 1 + Math.random() : 1 + Math.random() * 2; 

            s.style.left = x + '%';
            s.style.top = y + '%';
            s.style.width = size + 'px';
            s.style.height = size + 'px';

            s.style.setProperty('--duration', (2 + Math.random() * 4) + 's');
            s.style.animationDelay = (Math.random() * 5) + 's';

            container.appendChild(s);
            stars.push({ el: s, initialY: y, speed: z });
        }

        let lastScrollY = window.scrollY;

        function animateStars() {
            let currentScrollY = window.scrollY;
            
            // Pima spidi ya scroll
            let velocity = Math.abs(currentScrollY - lastScrollY);
            lastScrollY = currentScrollY;

            // Weka ukomo wa jinsi nyota zinavyovutika (Stretch)
            const stretch = Math.max(1, Math.min(1 + velocity * 0.05, 3));

            stars.forEach(star => {
                if (star.speed === 0) {
                    star.el.style.transform = 'scaleY(1)';
                    return;
                }
                
                // Nyota kusogea juu kulingana na scroll
                let pos = (star.initialY - (currentScrollY * star.speed * 0.05)) % 100;
                if (pos < 0) pos += 100; 

                star.el.style.top = pos + '%';
                star.el.style.transform = `scaleY(${stretch})`;
            });

            requestAnimationFrame(animateStars);
        }
        
        requestAnimationFrame(animateStars);
    });
</script>